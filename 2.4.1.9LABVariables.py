kilometers = 12.25
miles = 7.38

miles_to_kilometers = miles * 1.61
kilometers_to_miles = kilometers * 0.621118012421

print(miles, "miles is", round(miles_to_kilometers, 2), "kilometers")
print(kilometers, "kilometers is", round(kilometers_to_miles, 2), "miles")

celcius = 30
farenheit = 212

celcius_to_farenheit = celcius * 9/5 + 32
farenheit_to_celcius = (farenheit - 32) * 5/9

print(celcius, "temperature is", round(celcius_to_farenheit, 2), "farenheit")
print(farenheit, "temperature is", round(farenheit_to_celcius, 2), "celcius")

